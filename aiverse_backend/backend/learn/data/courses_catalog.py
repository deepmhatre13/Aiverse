def _lessons(course_slug, titles_queries):
    """Build lesson list from (title, youtube_query, duration) tuples."""
    return [
        {
            "order": i + 1,
            "title": t[0],
            "youtube_query": t[1],
            "duration_minutes": t[2] if len(t) > 2 else 18,
            "concept_tag": course_slug.split("-")[0],
            "learning_objectives": [f"Understand {t[0].lower()}"],
        }
        for i, t in enumerate(titles_queries)
    ]


